    /**
     * @return array{year: int, month: int, day: int}|null
     */
    public static function fromAd(CarbonInterface|string $date): ?array
    {
        $ad = Carbon::parse($date instanceof CarbonInterface ? $date->toDateString() : $date, 'UTC')->startOfDay();
        $days = (int) Carbon::parse(self::EPOCH_AD, 'UTC')->diffInDays($ad, false);

        if ($days < 0) {
            return null;
        }

        foreach (self::MONTH_DAYS as $year => $months) {
            $yearDays = array_sum($months);
            if ($days >= $yearDays) {
                $days -= $yearDays;

                continue;
            }

            foreach ($months as $index => $monthDays) {
                if ($days < $monthDays) {
                    return ['year' => $year, 'month' => $index + 1, 'day' => $days + 1];
                }
                $days -= $monthDays;
            }
        }

        return null;
    }

    /** AD date for a BS date, or null when out of range or invalid. */
    public static function toAd(int $year, int $month, int $day): ?Carbon
    {
        $months = self::MONTH_DAYS[$year] ?? null;
        if ($months === null || $month < 1 || $month > 12 || $day < 1 || $day > $months[$month - 1]) {
            return null;
        }

        $days = 0;
        for ($y = self::FIRST_YEAR; $y < $year; $y++) {
            $days += array_sum(self::MONTH_DAYS[$y]);
        }
        $days += array_sum(array_slice($months, 0, $month - 1)) + $day - 1;

        return Carbon::parse(self::EPOCH_AD, 'UTC')->addDays($days);
    }

    /** "2082-06-09" style BS date, or null when out of range. */
    public static function format(CarbonInterface|string|null $date): ?string
    {
        $bs = $date === null ? null : self::fromAd($date);

        return $bs === null ? null : sprintf('%04d-%02d-%02d', $bs['year'], $bs['month'], $bs['day']);
    }

    /** "9 Aswin 2082" style BS date, or null when out of range. */
    public static function formatLong(CarbonInterface|string|null $date): ?string
    {
        $bs = $date === null ? null : self::fromAd($date);

        return $bs === null ? null : $bs['day'].' '.self::MONTHS[$bs['month'] - 1].' '.$bs['year'];
    }

    /** "Aswin 2082" for the BS month the given AD date falls in. */
    public static function monthLabel(CarbonInterface|string $date): ?string
    {
        $bs = self::fromAd($date);

        return $bs === null ? null : self::MONTHS[$bs['month'] - 1].' '.$bs['year'];
    }
